import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import colors from "picocolors";

export const DOCKERFILE_CONTENT = `# Multi-stage Dockerfile generated by shard
FROM node:22-alpine AS builder
WORKDIR /app

# Install dependencies
COPY package*.json pnpm-lock*.yaml* ./
RUN npm install -g pnpm && pnpm install --frozen-lockfile || npm install

# Copy source and build
COPY . .
RUN npx shard build

# Production Runner Stage
FROM node:22-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production

COPY package*.json pnpm-lock*.yaml* ./
RUN npm install -g pnpm && pnpm install --prod || npm install --omit=dev

COPY --from=builder /app/.shard /app/.shard
COPY --from=builder /app/shard.config.* /app/

EXPOSE 3000
CMD ["node", ".shard/dist/runner.js"]
`;

export async function runDockerBuild(tag = "shard-bot:latest"): Promise<void> {
  const rootDir = process.cwd();
  const dockerfilePath = path.join(rootDir, "Dockerfile");

  if (!fs.existsSync(dockerfilePath)) {
    fs.writeFileSync(dockerfilePath, DOCKERFILE_CONTENT, "utf-8");
    console.log(colors.green("🐳 Generated production Dockerfile."));
  }

  console.log(colors.cyan(`\n🐳 Building Docker image: ${tag}...`));
  const proc = spawn("docker", ["build", "-t", tag, "."], {
    stdio: "inherit",
    cwd: rootDir,
    shell: true,
  });

  proc.on("exit", (code) => {
    if (code === 0) {
      console.log(colors.green(`\n✅ Docker image '${tag}' built successfully!`));
    } else {
      process.exit(code ?? 1);
    }
  });
}

export async function runDockerRun(
  tag = "shard-bot:latest",
  port = "3000"
): Promise<void> {
  console.log(colors.cyan(`\n🐳 Running Docker container '${tag}' on port ${port}...`));
  const proc = spawn(
    "docker",
    ["run", "--env-file", ".env", "-p", `${port}:${port}`, tag],
    {
      stdio: "inherit",
      cwd: process.cwd(),
      shell: true,
    }
  );

  proc.on("exit", (code) => {
    process.exit(code ?? 0);
  });
}
